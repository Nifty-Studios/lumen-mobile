// Prepares the editor webview's CSS, which Metro can't load as published: it drops @import
// (BlockNote and Mantine stylesheets are mostly @imports) and url() files (@fontsource fonts).
// - src/components/editor.css: BlockNote + Mantine styles with every @import inlined.
// - src/components/editorFonts.ts: Fraunces (titles, headings) as data URLs, so it works offline.
// Run `pnpm editor-assets` after updating BlockNote or @fontsource-variable/fraunces.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";

const root = createRequire(import.meta.url);
const out = (file) => new URL(`../src/components/${file}`, import.meta.url);

// --- styles ---
const seen = new Set();
function inline(file) {
  if (seen.has(file)) return "";
  seen.add(file);
  const from = createRequire(file);
  return readFileSync(file, "utf8")
    .replace(/^@charset[^;]*;/m, "")
    .replace(/@import\s+(?:url\()?\s*["']([^"']+)["']\s*\)?\s*;/g, (_, spec) =>
      inline(spec.startsWith(".") ? resolve(dirname(file), spec) : from.resolve(spec)),
    );
}
const styles = inline(root.resolve("@blocknote/mantine/style.css"));
const urls = [...styles.matchAll(/url\(\s*["']?(?!data:)([^"')]+)/g)].map((m) => m[1]);
if (urls.length) throw new Error(`Styles reference files Metro can't load: ${urls.join(", ")}`);
if (styles.includes("@import")) throw new Error("An @import was left in the styles");
writeFileSync(out("editor.css"), `/* Generated by scripts/editor-assets.mjs (pnpm editor-assets). Do not edit. */\n${styles}`);

// --- fonts ---
const fontDir = dirname(root.resolve("@fontsource-variable/fraunces/index.css"));
const fontCss = readFileSync(join(fontDir, "index.css"), "utf8");
const faces = [];
for (const [, body] of fontCss.matchAll(/@font-face\s*{([^}]*)}/g)) {
  const file = /url\(\.\/(files\/[^)]+)\)/.exec(body)?.[1];
  const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1];
  if (!file || !range || !/-(latin|latin-ext)-wght-normal\.woff2$/.test(file)) continue;
  const data = readFileSync(join(fontDir, file)).toString("base64");
  faces.push(
    `@font-face{font-family:"Fraunces Variable";font-style:normal;font-weight:100 900;font-display:block;` +
      `src:url(data:font/woff2;base64,${data}) format("woff2-variations");unicode-range:${range};}`,
  );
}
if (faces.length !== 2) throw new Error(`Expected the latin and latin-ext faces, found ${faces.length}`);
writeFileSync(
  out("editorFonts.ts"),
  `// Generated by scripts/editor-assets.mjs (pnpm editor-assets). Do not edit.\nexport const EDITOR_FONT_CSS = ${JSON.stringify(faces.join("\n"))};\n`,
);

console.log(`editor.css: ${seen.size} stylesheets inlined; editorFonts.ts: ${faces.length} Fraunces faces`);
