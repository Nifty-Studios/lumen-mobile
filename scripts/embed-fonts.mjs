// Embeds Fraunces (titles and headings) in the editor webview as data URLs. Metro can't load
// the url() files in @fontsource CSS inside a DOM component, and the editor has to work offline.
// Run `pnpm fonts` after updating @fontsource-variable/fraunces.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const dir = dirname(require.resolve("@fontsource-variable/fraunces/index.css"));
const css = readFileSync(join(dir, "index.css"), "utf8");

const faces = [];
for (const [, body] of css.matchAll(/@font-face\s*{([^}]*)}/g)) {
  const file = /url\(\.\/(files\/[^)]+)\)/.exec(body)?.[1];
  const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1];
  if (!file || !range || !/-(latin|latin-ext)-wght-normal\.woff2$/.test(file)) continue;
  const data = readFileSync(join(dir, file)).toString("base64");
  faces.push(
    `@font-face{font-family:"Fraunces Variable";font-style:normal;font-weight:100 900;font-display:block;` +
      `src:url(data:font/woff2;base64,${data}) format("woff2-variations");unicode-range:${range};}`,
  );
}
if (faces.length !== 2) throw new Error(`Expected the latin and latin-ext faces, found ${faces.length}`);

writeFileSync(
  new URL("../src/components/editorFonts.ts", import.meta.url),
  `// Generated by scripts/embed-fonts.mjs (pnpm fonts). Do not edit.\nexport const EDITOR_FONT_CSS = ${JSON.stringify(faces.join("\n"))};\n`,
);
console.log(`Embedded ${faces.length} Fraunces faces`);
